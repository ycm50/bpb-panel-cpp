#!/usr/bin/env python3
"""Generate src/assets_gen.cpp: embed the browser panel into the binary."""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent if len(sys.argv) < 2 else pathlib.Path(sys.argv[1])
assets = root / "assets"
out = root / "src" / "assets_gen.cpp"

pages = ["panel", "login", "error"]
chunks = []
chunks.append("// generated by tools/gen_assets.py - do not edit\n")
chunks.append("#include \"assets_gen.h\"\n\n")
chunks.append("#include <string>\n\n")
chunks.append("namespace bpb::assets {\n\n")

for page in pages:
    data = (assets / page / "index.html").read_bytes()
    chunks.append("static const unsigned char k_%s[] = {" % page)
    chunks.append(",".join(str(b) for b in data))
    chunks.append("};\n")
    chunks.append("static const std::size_t k_%s_len = sizeof(k_%s);\n\n" % (page, page))

icon = (assets / "favicon.ico").read_bytes()
chunks.append("static const unsigned char k_icon[] = {")
chunks.append(",".join(str(b) for b in icon))
chunks.append("};\n")
chunks.append("static const std::size_t k_icon_len = sizeof(k_icon);\n\n")

chunks.append("const char* page(const char* name, std::size_t& len) {\n")
for page in pages:
    chunks.append("    if (std::string(name) == \"%s\") { len = k_%s_len; return reinterpret_cast<const char*>(k_%s); }\n" % (page, page, page))
chunks.append("    len = 0;\n    return nullptr;\n}\n\n")
chunks.append("const char* icon(std::size_t& len) {\n")
chunks.append("    len = k_icon_len;\n    return reinterpret_cast<const char*>(k_icon);\n}\n\n")
chunks.append("} // namespace bpb::assets\n")

out.write_text("".join(chunks), encoding="utf-8")
print("wrote", out, out.stat().st_size, "bytes")
